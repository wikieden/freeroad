const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {initialize, composeShadow, sections, composeClash} = require('../scripts/build-private-config.cjs');
const root = path.resolve(__dirname, '..');
const base = '[General]\nupdate-url = https://example.org/public.conf\n[Proxy Group]\nAI = select,DIRECT\n[Rule]\nDOMAIN-SUFFIX,example.org,AI\nFINAL,DIRECT\n[Host]\nlocalhost = 127.0.0.1\n';
const own = base.replace('[Proxy Group]', '[Proxy]\nMyNode = socks5,example.net,1080,u,p\n[Proxy Group]').replace('AI = select,DIRECT','AI = select,DIRECT,MyNode');
const overlay = initialize(base, own);
assert.deepEqual(overlay.prependRules, []);
assert.deepEqual(overlay.removeRules, []);
assert(!JSON.stringify(overlay).includes('DOMAIN-SUFFIX'));
const nextBase = base.replace('FINAL,DIRECT', 'DOMAIN-SUFFIX,new.example,AI\nFINAL,DIRECT');
const built = composeShadow(nextBase, overlay);
assert(built.includes('DOMAIN-SUFFIX,new.example,AI'));
assert(built.includes('AI = select,DIRECT,MyNode'));
assert(!built.includes('https://example.org/public.conf'));
assert.deepEqual(sections(built).Rule, sections(nextBase).Rule);
const custom = structuredClone(overlay);
custom.prependRules.push('DOMAIN-SUFFIX,private.example,DIRECT');
assert.equal(sections(composeShadow(nextBase,custom)).Rule[0],custom.prependRules[0]);
custom.prependRules.push('FINAL,DIRECT');
assert.throws(() => composeShadow(base,custom), /one FINAL/);
const broken = structuredClone(overlay); broken.groups.remove.push('AI');
delete broken.groups.set.AI;
assert.throws(() => composeShadow(base,broken), /missing policy/);
assert.throws(() => initialize(base,own.replace('DOMAIN-SUFFIX,example.org,AI\nFINAL,DIRECT','FINAL,DIRECT\nDOMAIN-SUFFIX,example.org,AI')), /Reordered/);
assert.throws(() => composeClash('',{rules:['MATCH,DIRECT']}), /duplicate/);
const fragment = {'proxy-providers': {airport: {type:'http',url:'https://example.org/sub',path:'./providers/test.yaml',interval:3600}}};
const original = JSON.stringify(fragment);
const out = composeClash(fs.readFileSync(path.join(root,'clash-global-residential-extend-script.js'),'utf8'),fragment);
assert(out.rules.includes('RULE-SET,freeroad-proxy,🎯 全局分流'));
assert.equal(JSON.stringify(fragment), original, 'Never mutate private source');
assert.deepEqual(composeClash(fs.readFileSync(path.join(root,'clash-global-residential-extend-script.js'),'utf8'),fragment),out);
console.log('PASS: public rule refresh, private delta, source immutability, deterministic generation, policy validation, unsafe migration rejection');
